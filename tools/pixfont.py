COLW = [2, 1, 2, 1, 2, 1, 2]
ROWS = 9

def wide(ch):
    """list of rows (lists of 0/1) after column widening; width in px"""
    rows = list(G[ch]) + ['.' * len(G[ch][0])] * (ROWS - len(G[ch]))
    w = len(rows[0]); out = []
    for r in rows:
        line = []
        for c in range(w):
            line += [1 if r[c] == '#' else 0] * COLW[c]
        out.append(line)
    return out, sum(COLW[:w])
